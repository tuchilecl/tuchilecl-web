const LANG_STORAGE_KEY = 'tuchilecl-lang';
const SUPPORTED_LANGS = ['es', 'en', 'pt', 'de'];

function getCurrentLang() {
  const saved = localStorage.getItem(LANG_STORAGE_KEY);
  return SUPPORTED_LANGS.includes(saved) ? saved : 'es';
}

function translate(key, lang) {
  const activeLang = lang || getCurrentLang();
  return (translations[activeLang] && translations[activeLang][key]) || translations.es[key] || key;
}

function applyLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;

  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = translate(el.getAttribute('data-i18n'), lang);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', translate(el.getAttribute('data-i18n-placeholder'), lang));
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', translate(el.getAttribute('data-i18n-aria-label'), lang));
  });

  document.querySelectorAll('.lang-option').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  const currentLabel = document.getElementById('langCurrentLabel');
  if (currentLabel) currentLabel.textContent = lang.toUpperCase();

  localStorage.setItem(LANG_STORAGE_KEY, lang);
}

